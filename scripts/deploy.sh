#!/bin/bash
# Скрипт автоматического развертывания проекта на целевом сервере

set -e

echo "🚀 Развертывание проекта «Твой Путь: Абстрактный Репетитор» v5.0..."

# 1. Получение последних изменений из репозитория
echo "📥 Обновление кода из git..."
git pull origin $(git rev-parse --abbrev-ref HEAD)

# 2. Проверка наличия .env
if [ ! -f .env ]; then
    echo "⚠️ Файл .env не найден! Создаю из .env.example..."
    cp .env.example .env
    echo "❗ Пожалуйста, укажите реальные токены в .env перед запуском."
fi

# 3. Пересборка и запуск контейнеров
echo "🐳 Сборка и запуск контейнеров Docker Compose..."
docker-compose up -d --build

# 4. Проверка статуса
echo "🔍 Проверка состояния контейнеров..."
docker-compose ps

echo "🎉 Деплой успешно завершен! Сервисы доступны на портах 8000, 8001, 8002."
