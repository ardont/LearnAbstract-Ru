def generate_pdf(output_path: Path):
    output_path.parent.mkdir(parents=True, exist_ok=True)

    from reportlab.lib.pagesizes import letter
    from reportlab.pdfgen import canvas
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    font_name = "Helvetica"
    candidate_fonts = [
        ("Arial", "C:/Windows/Fonts/arial.ttf"),
        ("DejaVuSans", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"),
        ("LiberationSans", "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf")
    ]
    for name, path in candidate_fonts:
        if os.path.exists(path):
            pdfmetrics.registerFont(TTFont(name, path))
            font_name = name
            print(f"Используем шрифт: {name} ({path})")
            break

    c = canvas.Canvas(str(output_path), pagesize=letter)
    page_width, page_height = letter

    # Титульный блок
    y = page_height - 60
    c.setFont(font_name, 16)
    c.drawString(50, y, "ТЕОРЕТИЧЕСКИЙ КУРС: АЛГЕБРА И ЕСТЕСТВОЗНАНИЕ (7-8 КЛАСС)")
    y -= 24
    c.setFont(font_name, 11)
    c.drawString(50, y, "Академический справочник для системы «Твой Путь: Абстрактный Репетитор»")
    y -= 30

    page_num = 1
    total_chars = 0

    for title, paragraphs in SECTIONS:
        # Проверяем место для заголовка
        if y < 100:
            c.setFont(font_name, 9)
            c.drawRightString(page_width - 50, 30, f"Страница {page_num}")
            c.showPage()
            page_num += 1
            y = page_height - 60

        c.setFont(font_name, 13)
        c.drawString(50, y, title)
        y -= 22

        c.setFont(font_name, 10)
        for p in paragraphs:
            total_chars += len(p)
            # Разбиение длинных строк
            words = p.split(" ")
            current_line = []
            for word in words:
                test_line = " ".join(current_line + [word])
                if len(test_line) > 85:
                    if y < 60:
                        c.setFont(font_name, 9)
                        c.drawRightString(page_width - 50, 30, f"Страница {page_num}")
                        c.showPage()
                        page_num += 1
                        y = page_height - 60
                        c.setFont(font_name, 10)
                    c.drawString(50, y, " ".join(current_line))
                    y -= 14
                    current_line = [word]
                else:
                    current_line.append(word)

            if current_line:
                if y < 60:
                    c.setFont(font_name, 9)
                    c.drawRightString(page_width - 50, 30, f"Страница {page_num}")
                    c.showPage()
                    page_num += 1
                    y = page_height - 60
                    c.setFont(font_name, 10)
                c.drawString(50, y, " ".join(current_line))
                y -= 18

        y -= 10

    c.setFont(font_name, 9)
    c.drawRightString(page_width - 50, 30, f"Страница {page_num}")
    c.showPage()
    c.save()

