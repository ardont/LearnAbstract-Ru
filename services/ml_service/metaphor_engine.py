def get_metaphor(topic: str, interest: str = "Футбол", grade: int = 7) -> Dict[str, Any]:
    """
    3-уровневый иерархический генератор аналогий:
    - Уровень 1: Точное совпадение (Exact Match).
    - Уровень 2: По предмету/категории (Subject Category).
    - Уровень 3: Общенаучный адаптивный шаблон (Universal General).
    """
    clean_topic = topic.lower().strip()
    interest_key = interest if interest in ["Футбол", "Видеоигры", "Музыка", "Космос", "Кино"] else "Футбол"

    # --- УРОВЕНЬ 1: Точное совпадение ---
    for exact_key, interest_dict in EXACT_TOPICS.items():
        if exact_key in clean_topic:
            data = interest_dict.get(interest_key) or interest_dict.get("Футбол")
            if data:
                text = latex_to_unicode(data["text"])
                quiz = data["quiz"].copy()
                quiz["quiz_id"] = str(uuid.uuid4())
                quiz["topic"] = topic
                return {
                    "text": text,
                    "source": "fallback_exact",
                    "level": 1,
                    "quiz": quiz
                }

    # --- УРОВЕНЬ 2: Категория/Предмет ---
    for cat_name, cat_data in SUBJECT_CATEGORIES.items():
        if any(kw in clean_topic for kw in cat_data["keywords"]):
            interest_text = f"сфере «{interest_key}»"
            formatted_text = cat_data["template"].format(
                interest_name=interest_text,
                topic=topic
            )
            quiz = cat_data["quiz"].copy()
            quiz["quiz_id"] = str(uuid.uuid4())
            quiz["topic"] = topic
            return {
                "text": latex_to_unicode(formatted_text),
                "source": "fallback_subject",
                "level": 2,
                "quiz": quiz
            }

    # --- УРОВЕНЬ 3: Общенаучный универсальный General ---
    general_text = (
        f"🌟 Давай разберём тему «{topic}» через призму твоего увлечения ({interest_key})!\n\n"
        f"В науке любое сложное явление состоит из трёх простых вещей:\n"
        f"1. **Правила системы** — законы, которые нельзя нарушать (как правила игры в {interest_key}).\n"
        f"2. **Действующие силы** — факторы, которые толкают процесс вперёд.\n"
        f"3. **Итоговый результат** — состояние, к которому всё стремится (победный гол или завершённый уровень).\n\n"
        f"Когда ты встречаешь формулу или определение по теме «{topic}», представляй, какая именно деталь в механике {interest_key} отвечает за этот шаг. Это превращает абстрактную теорию в живой и понятный навык!"
    )

    general_quiz = {
        "quiz_id": str(uuid.uuid4()),
        "topic": topic,
        "question": f"Какой подход лучше всего помогает освоить сложную тему «{topic}»?",
        "options": [
            "Зубрить сухие формулы без понимания смысла",
            "Связывать абстрактные законы с понятными жизненными аналогиями и практикой",
            "Никогда не задавать вопросов учителю",
            "Надеяться на случайность"
        ],
        "correct_option_index": 1,
        "explanation": "Метод аналогий связывает новые абстрактные понятия с уже сформированными нейронными связями в твоём мозге."
    }

    return {
        "text": latex_to_unicode(general_text),
        "source": "fallback_general",
        "level": 3,
        "quiz": general_quiz
    }
