def get_catalog_metaphor(topic: str, interest: str = "Футбол") -> dict:
    """Извлекает точную метафору из каталога 100 готовых тем."""
    clean_topic = topic.lower().strip()
    clean_interest = interest if interest in ["Футбол", "Баскетбол", "Видеоигры", "Музыка", "Космос"] else "Футбол"

    # Ищем точное или подстрочное совпадение с темами каталога
    for t_key, hobbies_dict in FALLBACK_CATALOG.items():
        if t_key in clean_topic or clean_topic in t_key:
            data = hobbies_dict.get(clean_interest) or hobbies_dict.get("Футбол")
            if data:
                return {
                    "text": data["text"],
                    "quiz": data["quiz"],
                    "topic": t_key,
                    "interest": clean_interest,
                    "source": "fallback_catalog"
                }

    return None
